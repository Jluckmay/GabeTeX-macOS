import Foundation

/// A single LaTeX mathematical symbol or construct shown in the sidebar table.
nonisolated struct MathSymbol: Identifiable, Hashable, Sendable {
    let id: String
    let display: String
    let code: String
    let snippet: String?
    let name: String
    let keywords: [String]
    let pkg: String?

    init(
        _ display: String,
        _ code: String,
        snippet: String? = nil,
        name: String,
        keywords: [String] = [],
        pkg: String? = nil
    ) {
        self.id = "\(code)|\(display)"
        self.display = display
        self.code = code
        self.snippet = snippet
        self.name = name
        self.keywords = keywords
        self.pkg = pkg
    }

    /// Template passed on click (expands tab stops when defined).
    var insertionText: String { snippet ?? code }
}

