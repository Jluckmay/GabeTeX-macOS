    static func filtered(query: String) -> [MathSymbolCategory] {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !q.isEmpty else { return categories }
        return categories.compactMap { category in
            let title = String(localized: String.LocalizationValue(category.titleKey)).lowercased()
            if title.contains(q) {
                return category
            }
            let matching = category.symbols.filter { sym in
                sym.code.lowercased().contains(q)
                    || sym.name.lowercased().contains(q)
                    || sym.display.lowercased().contains(q)
                    || (sym.pkg?.lowercased().contains(q) ?? false)
                    || sym.keywords.contains(where: { $0.lowercased().contains(q) })
            }
            guard !matching.isEmpty else { return nil }
            return MathSymbolCategory(id: category.id, titleKey: category.titleKey, icon: category.icon, symbols: matching)
        }
    }
